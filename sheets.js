// 模範解答をシートの項目・用語へ変換する。
// 戻り値: { answers: {sectionId: [terms]}, dropped: シートに存在せず採点から外れた語数 }
function sheetAnswers(wine, sheet) {
  if (!sheet || sheet.vocab === VOCAB) return { answers: wine.answers, dropped: 0 };
  const src = wine.answers;
  const out = {};
  let dropped = 0;
  for (const sec of sheet.vocab[wine.color]) {
    const raw = sec.from ? sec.from.flatMap(id => src[id] || []) : (src[sec.id] || []);
    const mapped = [];
    for (const t of raw) {
      const m = sheet.aliases[t] || t;
      if (sec.terms.includes(m)) { if (!mapped.includes(m)) mapped.push(m); }
      else dropped++;
    }
    out[sec.id] = mapped;
  }
  return { answers: out, dropped };
}
